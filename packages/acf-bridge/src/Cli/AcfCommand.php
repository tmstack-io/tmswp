<?php

declare(strict_types=1);

namespace TMSWP\AcfBridge\Cli;

use FilesystemIterator;
use SplFileInfo;
use TMSWP\AcfBridge\AcfBridge;
use TMSWP\AcfBridge\BridgeConfig;
use TMSWP\AcfBridge\Exception\AcfBridgeException;
use TMSWP\AcfBridge\Exception\AcfBridgeRuntimeException;
use TMSWP\AcfBridge\Generate\CloneResolver;
use TMSWP\AcfBridge\Generate\GeneratedFile;
use TMSWP\AcfBridge\Generate\Generator;
use TMSWP\AcfBridge\Generate\GeneratorContext;
use TMSWP\AcfBridge\Generate\Report;
use TMSWP\AcfBridge\Json\AcfJsonRepository;
use TMSWP\AcfBridge\Json\FieldGroup;
use TMSWP\AcfBridge\Manifest\ManagedKeyCollector;
use TMSWP\AcfBridge\Mapping\LocationResolver;
use TMSWP\Core\Exception\DuplicateMetaKeyException;
use TMSWP\Core\Kernel\Kernel;
use TMSWP\Core\Meta\MetaSchemaRegistry;
use WP_CLI;

/**
 * `wp tmswp acf sync|check`。対象は`--app=`で選んだKernelに登録したAcfBridgeの構成で、AcfBridgeを登録したKernelが
 * 1つなら`--app=`を省略できる。終了コードはdocs/09 §5.1のとおり(sync: 0成功 / 1 E* または書き込みの失敗 / 2環境・設定の
 * 誤り、check: 0差分なし / 1差分あり、または --strictでW* あり / 2 E* または環境・設定の誤り)。
 */
final class AcfCommand
{
    private const GENERATED_MARKER = '@generated by tmswp/acf-bridge';

    private const SYNC_USAGE = 'Usage: wp tmswp acf sync [--app=<namespace>] [--dry-run]';

    private const CHECK_USAGE = 'Usage: wp tmswp acf check [--app=<namespace>] [--strict]';

    /**
     * Generates the ACF typed accessor classes and AcfManifest from acf-json.
     *
     * ## OPTIONS
     *
     * [--app=<namespace>]
     * : The app namespace of the kernel that registers AcfBridge. Optional when only one kernel registers it.
     *
     * [--dry-run]
     * : Show the differences without writing files.
     *
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     */
    public function sync(array $args, array $assocArgs): void
    {
        if (!class_exists('WP_CLI')) {
            throw new AcfBridgeRuntimeException('WP_CLI is not available');
        }

        $outcome = $this->runSync($args, $assocArgs);

        foreach ($outcome['lines'] as $line) {
            WP_CLI::line($line);
        }

        if ($outcome['status'] !== 0) {
            WP_CLI::halt($outcome['status']);

            return;
        }

        WP_CLI::success($outcome['message']);
    }

    /**
     * Checks that the generated files are in sync with acf-json.
     *
     * ## OPTIONS
     *
     * [--app=<namespace>]
     * : The app namespace of the kernel that registers AcfBridge. Optional when only one kernel registers it.
     *
     * [--strict]
     * : Fail on warnings too.
     *
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     */
    public function check(array $args, array $assocArgs): void
    {
        if (!class_exists('WP_CLI')) {
            throw new AcfBridgeRuntimeException('WP_CLI is not available');
        }

        $outcome = $this->runCheck($args, $assocArgs);

        foreach ($outcome['lines'] as $line) {
            WP_CLI::line($line);
        }

        if ($outcome['status'] !== 0) {
            WP_CLI::halt($outcome['status']);

            return;
        }

        WP_CLI::success($outcome['message']);
    }

    /**
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     *
     * @return array{lines: list<string>, status: int, message: string}
     */
    private function runSync(array $args, array $assocArgs): array
    {
        try {
            $config = $this->bridge($args, $assocArgs, ['app', 'dry-run'], self::SYNC_USAGE)->config();
            $result = $this->generate($config);
        } catch (AcfBridgeException $exception) {
            return ['lines' => [$exception->getMessage()], 'status' => 2, 'message' => ''];
        }

        $lines = $this->diagnostics($result['report']);

        if ($result['report']->hasErrors()) {
            return ['lines' => [...$lines, 'ACF bridge generation failed'], 'status' => 1, 'message' => ''];
        }

        if (\array_key_exists('dry-run', $assocArgs)) {
            return ['lines' => [...$lines, ...$this->differenceLines($this->differences($config, $result['report']))], 'status' => 0, 'message' => 'ACF bridge sync dry-run completed'];
        }

        try {
            $lines = [...$lines, ...$this->writeGeneratedFiles($config, $result['report']), ...$this->deleteOrphans($config, $result['report'])];
        } catch (AcfBridgeRuntimeException $exception) {
            return ['lines' => [...$lines, $exception->getMessage()], 'status' => 1, 'message' => ''];
        }

        return ['lines' => $lines, 'status' => 0, 'message' => 'ACF bridge sync completed'];
    }

    /**
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     *
     * @return array{lines: list<string>, status: int, message: string}
     */
    private function runCheck(array $args, array $assocArgs): array
    {
        try {
            $config = $this->bridge($args, $assocArgs, ['app', 'strict'], self::CHECK_USAGE)->config();
            $result = $this->generate($config);
        } catch (AcfBridgeException $exception) {
            return ['lines' => [$exception->getMessage()], 'status' => 2, 'message' => ''];
        }

        $lines = $this->diagnostics($result['report']);

        if ($result['report']->hasErrors()) {
            return ['lines' => [...$lines, 'ACF bridge generation failed'], 'status' => 2, 'message' => ''];
        }

        $diffs = $this->differences($config, $result['report']);

        if ($diffs !== []) {
            return ['lines' => [...$lines, ...$this->differenceLines($diffs), 'Run: wp tmswp acf sync (composer acf:sync)'], 'status' => 1, 'message' => ''];
        }

        if (\array_key_exists('strict', $assocArgs) && $result['report']->warnings() !== []) {
            return ['lines' => [...$lines, 'ACF bridge strict check failed with warnings'], 'status' => 1, 'message' => ''];
        }

        return [
            'lines' => $lines,
            'status' => 0,
            'message' => 'ACF bridge is in sync. (' . \count($result['report']->files()) . ' files, source-hash sha256:' . $result['sourceHash'] . ')',
        ];
    }

    /**
     * 引数を検査し、対象のKernelに登録したAcfBridgeを返す。
     *
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     * @param list<string> $allowedOptions
     *
     * @throws AcfBridgeRuntimeException 引数の誤り、対象のKernelが決まらない場合
     */
    private function bridge(array $args, array $assocArgs, array $allowedOptions, string $usage): AcfBridge
    {
        if ($args !== [] || array_diff(array_keys($assocArgs), $allowedOptions) !== []) {
            throw new AcfBridgeRuntimeException($usage);
        }

        $kernels = [];

        foreach (Kernel::all() as $namespace => $kernel) {
            foreach ($kernel->config()->extensions as $extension) {
                if ($extension instanceof AcfBridge) {
                    $kernels[$namespace] = $kernel;
                }
            }
        }

        $app = $assocArgs['app'] ?? null;
        $registered = implode(', ', array_keys($kernels));

        if ($app === null) {
            if (\count($kernels) !== 1) {
                throw new AcfBridgeRuntimeException($kernels === []
                    ? 'AcfBridge is not registered to any booted kernel; pass new AcfBridge() in the extensions of KernelConfig'
                    : "--app=<namespace> is required because AcfBridge is registered to more than one kernel: {$registered}");
            }

            return AcfBridge::forKernel(reset($kernels));
        }

        if (!\is_string($app) || !\array_key_exists(trim($app, '\\'), $kernels)) {
            throw new AcfBridgeRuntimeException('--app must be the app namespace of a kernel that registers AcfBridge: ' . ($registered !== '' ? $registered : '(none)'));
        }

        return AcfBridge::forKernel($kernels[trim($app, '\\')]);
    }

    /**
     * @throws AcfBridgeException acf-jsonの読み込みの失敗、オプションページのpost_idの指定の食い違い
     *
     * @return array{report: Report, sourceHash: string}
     */
    private function generate(BridgeConfig $config): array
    {
        $json = (new AcfJsonRepository($config->jsonDirs))->load();
        $report = (new Generator(new LocationResolver()))->generate(
            $json->fieldGroups,
            new GeneratorContext(
                config: $config,
                optionsPagePostIds: $this->optionsPagePostIds($json->optionsPagePostIds, $config),
                sourceHash: $json->sourceHash,
            ),
        );

        return [
            'report' => new Report(
                $report->files(),
                [...$report->errors(), ...$this->metaSchemaConflictErrors($config, $json->fieldGroups)],
                [...$json->warnings, ...$report->warnings()],
                $report->infos(),
            ),
            'sourceHash' => $json->sourceHash,
        ];
    }

    /**
     * オプションページのmenu_slug => post_id。acf-jsonのui_options_pageのpost_idと、BridgeConfigの
     * optionsPagePostIdsを合わせる(ACFの実行時には問い合わせない。生成結果を環境に依存させないため)。
     *
     * @param array<string, string> $postIds acf-jsonのui_options_pageのmenu_slug => post_id
     *
     * @throws AcfBridgeRuntimeException 同じページに違うpost_idを指定した場合
     *
     * @return array<string, string>
     */
    private function optionsPagePostIds(array $postIds, BridgeConfig $config): array
    {

        foreach ($config->optionsPagePostIds as $menuSlug => $postId) {
            if (\array_key_exists($menuSlug, $postIds) && $postIds[$menuSlug] !== $postId) {
                throw new AcfBridgeRuntimeException("E102: options page '{$menuSlug}' has post_id '{$postIds[$menuSlug]}' in acf-json and '{$postId}' in BridgeConfig optionsPagePostIds");
            }

            $postIds[$menuSlug] = $postId;
        }

        ksort($postIds, SORT_STRING);

        return $postIds;
    }

    /**
     * E101: ACFの管理キーと、起動中のKernelの#[MetaSchema]の宣言の重複。管理キーはcloneを解決したグループから
     * 集め、判定は実行時の申告(AcfBridge::markManagedKey())を各Kernelのレジストリの複製に行って、その例外の
     * メッセージを使う(実行時と同じ判定・同じ説明にする。複製なので起動中のレジストリは変えない)。
     *
     * @param list<FieldGroup> $groups
     *
     * @return list<string>
     */
    private function metaSchemaConflictErrors(BridgeConfig $config, array $groups): array
    {
        // cloneの解決の誤り(E004・E005)はGeneratorが報告する
        $cloneErrors = [];
        $managedKeys = (new ManagedKeyCollector())->collect((new CloneResolver())->resolve($groups, $cloneErrors), $config);
        $errors = [];

        foreach (Kernel::all() as $kernel) {
            $registry = clone $kernel->container()->get(MetaSchemaRegistry::class);

            foreach ($managedKeys as $managedKey) {
                try {
                    AcfBridge::markManagedKey($registry, $managedKey);
                } catch (DuplicateMetaKeyException $exception) {
                    $errors[] = 'E101: ' . $exception->getMessage();
                }
            }
        }

        sort($errors, SORT_STRING);

        return array_values(array_unique($errors));
    }

    /** @return list<array{type: string, path: string}> */
    private function differences(BridgeConfig $config, Report $report): array
    {
        $diffs = [];
        $expected = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
            $path = $this->pathFor($config, $file);

            if (!is_file($path)) {
                $diffs[] = ['type' => 'missing', 'path' => $file->relativePath];
                continue;
            }

            $contents = file_get_contents($path);

            if ($contents === false || $contents !== $file->contents) {
                $diffs[] = ['type' => 'modified', 'path' => $file->relativePath];
            }
        }

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (!\array_key_exists($relativePath, $expected) && $this->hasGeneratedMarker($path)) {
                $diffs[] = ['type' => 'orphan', 'path' => $relativePath];
            }
        }

        return $diffs;
    }

    /**
     * @throws AcfBridgeRuntimeException 出力先の作成・書き込みに失敗した場合
     *
     * @return list<string>
     */
    private function writeGeneratedFiles(BridgeConfig $config, Report $report): array
    {
        if (!is_dir($config->outputDir) && !mkdir($config->outputDir, 0775, true) && !is_dir($config->outputDir)) {
            throw new AcfBridgeRuntimeException("E102: failed to create output directory {$config->outputDir}");
        }

        $lines = [];

        foreach ($report->files() as $file) {
            $path = $this->pathFor($config, $file);
            $tmp = $path . '.tmp';

            if (file_put_contents($tmp, $file->contents) === false) {
                throw new AcfBridgeRuntimeException("E102: failed to write generated file {$tmp}");
            }

            if (!rename($tmp, $path)) {
                throw new AcfBridgeRuntimeException("E102: failed to move generated file {$tmp} to {$path}");
            }

            $lines[] = "write: {$file->relativePath}";
        }

        return $lines;
    }

    /**
     * @throws AcfBridgeRuntimeException 孤児の削除に失敗した場合
     *
     * @return list<string>
     */
    private function deleteOrphans(BridgeConfig $config, Report $report): array
    {
        $expected = [];
        $lines = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
        }

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (\array_key_exists($relativePath, $expected) || !$this->hasGeneratedMarker($path)) {
                continue;
            }

            if (!unlink($path)) {
                throw new AcfBridgeRuntimeException("E102: failed to delete orphan generated file {$relativePath}");
            }

            $lines[] = "delete: {$relativePath}";
        }

        return $lines;
    }

    /** @return list<string> */
    private function generatedPhpFiles(BridgeConfig $config): array
    {
        if (!is_dir($config->outputDir)) {
            return [];
        }

        $files = [];
        $iterator = new FilesystemIterator($config->outputDir, FilesystemIterator::SKIP_DOTS);

        foreach ($iterator as $fileInfo) {
            if (!$fileInfo instanceof SplFileInfo || !$fileInfo->isFile() || $fileInfo->getExtension() !== 'php') {
                continue;
            }

            $files[] = $fileInfo->getPathname();
        }

        sort($files, SORT_STRING);

        return $files;
    }

    private function hasGeneratedMarker(string $path): bool
    {
        $contents = file_get_contents($path);

        return \is_string($contents) && str_contains($contents, self::GENERATED_MARKER);
    }

    private function pathFor(BridgeConfig $config, GeneratedFile $file): string
    {
        return rtrim($config->outputDir, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR . $file->relativePath;
    }

    /** @return list<string> */
    private function diagnostics(Report $report): array
    {
        return [...$report->errors(), ...$report->warnings(), ...$report->infos()];
    }

    /**
     * @param list<array{type: string, path: string}> $diffs
     *
     * @return list<string>
     */
    private function differenceLines(array $diffs): array
    {
        return array_map(static fn(array $diff): string => $diff['type'] . ': ' . $diff['path'], $diffs);
    }
}
