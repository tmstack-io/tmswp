<?php

declare(strict_types=1);

namespace TMSWP\AcfBridge\Cli;

use Closure;
use FilesystemIterator;
use SplFileInfo;
use TMSWP\AcfBridge\AcfBridge;
use TMSWP\AcfBridge\BridgeConfig;
use TMSWP\AcfBridge\Exception\AcfBridgeException;
use TMSWP\AcfBridge\Exception\AcfBridgeRuntimeException;
use TMSWP\AcfBridge\Generate\GeneratedFile;
use TMSWP\AcfBridge\Generate\Generator;
use TMSWP\AcfBridge\Generate\GeneratorContext;
use TMSWP\AcfBridge\Generate\Report;
use TMSWP\AcfBridge\Generate\TypeMapper;
use TMSWP\AcfBridge\Json\AcfJsonRepository;
use TMSWP\AcfBridge\Json\FieldGroup;
use TMSWP\AcfBridge\Mapping\GenerationTarget;
use TMSWP\AcfBridge\Mapping\LocationResolver;
use TMSWP\AcfBridge\Mapping\TargetKind;
use TMSWP\Core\Exception\LogicException;
use TMSWP\Core\Kernel\Kernel;
use TMSWP\Core\Meta\MetaSchemaRegistry;
use TMSWP\Core\Meta\ObjectType;

final class AcfCommand
{
    private const GENERATED_MARKER = '@generated by tmswp/acf-bridge';

    /**
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     */
    public function sync(array $args, array $assocArgs): void
    {
        if ($args !== []) {
            $this->fail('Usage: wp tmswp acf sync [--dry-run]', 2);
        }

        $result = $this->generate();
        $this->printDiagnostics($result['report']);

        if ($result['report']->hasErrors()) {
            $this->fail('ACF bridge generation failed', 1);
        }

        $diffs = $this->differences($result['config'], $result['report']);

        if (\array_key_exists('dry-run', $assocArgs)) {
            $this->printDifferences($diffs);
            $this->success('ACF bridge sync dry-run completed');

            return;
        }

        $this->writeGeneratedFiles($result['config'], $result['report']);
        $this->deleteOrphans($result['config'], $result['report']);
        $this->success('ACF bridge sync completed');
    }

    /**
     * @param list<string> $args
     * @param array<string, mixed> $assocArgs
     */
    public function check(array $args, array $assocArgs): void
    {
        if ($args !== []) {
            $this->fail('Usage: wp tmswp acf check [--strict]', 2);
        }

        $result = $this->generate();
        $this->printDiagnostics($result['report']);

        if ($result['report']->hasErrors()) {
            $this->fail('ACF bridge generation failed', 2);
        }

        $diffs = $this->differences($result['config'], $result['report']);

        if ($diffs !== []) {
            $this->printDifferences($diffs);
            $this->line('Run: wp tmswp acf sync (composer acf:sync)');
            $this->halt(1);
        }

        if (\array_key_exists('strict', $assocArgs) && $result['report']->warnings() !== []) {
            $this->fail('ACF bridge strict check failed with warnings', 1);
        }

        $this->success('ACF bridge is in sync. (' . \count($result['report']->files()) . ' files, source-hash sha256:' . $result['sourceHash'] . ')');
    }

    /**
     * @return array{config: BridgeConfig, report: Report, sourceHash: string}
     */
    private function generate(): array
    {
        try {
            $config = AcfBridge::config();
            $repository = new AcfJsonRepository($config->jsonDirs);
            $sourceHash = $repository->sourceHash();
            $groups = $repository->fieldGroups();
            $report = (new Generator(new LocationResolver()))->generate(
                $groups,
                new GeneratorContext(
                    config: $config,
                    optionsPagePostIds: $repository->optionsPagePostIds(),
                    runtimePostIdResolver: $this->runtimePostIdResolver(),
                    sourceHash: $sourceHash,
                ),
            );
            $repositoryWarnings = $repository->warnings();

            if ($repositoryWarnings !== []) {
                $report = new Report(
                    $report->files(),
                    $report->errors(),
                    [...$repositoryWarnings, ...$report->warnings()],
                    $report->infos(),
                );
            }

            $conflicts = $this->metaSchemaConflictErrors($config, $groups);

            if ($conflicts !== []) {
                $report = new Report(
                    $report->files(),
                    [...$report->errors(), ...$conflicts],
                    $report->warnings(),
                    $report->infos(),
                );
            }
        } catch (AcfBridgeException $exception) {
            $this->fail($exception->getMessage(), 2);
        }

        return ['config' => $config, 'report' => $report, 'sourceHash' => $sourceHash];
    }

    /**
     * @param list<FieldGroup> $groups
     *
     * @return list<string>
     */
    private function metaSchemaConflictErrors(BridgeConfig $config, array $groups): array
    {
        $managedKeys = $this->managedKeys($config, $groups);
        $errors = [];

        if ($managedKeys === []) {
            return [];
        }

        foreach (Kernel::all() as $kernel) {
            $registry = $kernel->container()->get(MetaSchemaRegistry::class);

            foreach ($registry->schemas() as $registered) {
                foreach ($managedKeys as $managedKey) {
                    if (
                        $registered['objectType'] === $managedKey['objectType']
                        && $registered['schema']->key === $managedKey['metaKey']
                        && ($registered['subtype'] === $managedKey['subtype'] || $managedKey['subtype'] === 'all')
                    ) {
                        $errors[] = "E101: meta key '{$managedKey['metaKey']}' is declared by {$registered['entityClass']} and ACF group {$managedKey['groupKey']}";
                    }
                }
            }
        }

        sort($errors, SORT_STRING);

        return array_values(array_unique($errors));
    }

    /**
     * @param list<FieldGroup> $groups
     *
     * @return list<array{objectType: ObjectType, subtype: string, metaKey: string, groupKey: string}>
     */
    private function managedKeys(BridgeConfig $config, array $groups): array
    {
        $locations = new LocationResolver();
        $types = new TypeMapper();
        $keys = [];

        foreach ($groups as $group) {
            if (!$group->active) {
                continue;
            }

            foreach ($locations->resolve($group, $config) as $target) {
                $objectType = $this->objectTypeForTarget($target);

                if (!$objectType instanceof ObjectType) {
                    continue;
                }

                foreach ($group->fields as $field) {
                    if (!$types->storesValue($field) || $field->name === '' || $field->type === 'clone') {
                        continue;
                    }

                    $keys[] = [
                        'objectType' => $objectType,
                        'subtype' => $target->subtype,
                        'metaKey' => $field->name,
                        'groupKey' => $group->key,
                    ];
                }
            }
        }

        return $keys;
    }

    private function objectTypeForTarget(GenerationTarget $target): ?ObjectType
    {
        return match ($target->kind) {
            TargetKind::Post => ObjectType::Post,
            TargetKind::Term => ObjectType::Term,
            TargetKind::User => ObjectType::User,
            TargetKind::Options => null,
        };
    }

    private function runtimePostIdResolver(): Closure
    {
        return static function (string $menuSlug): ?string {
            if (!\function_exists('acf_get_options_page')) {
                return null;
            }

            $page = acf_get_options_page($menuSlug);

            if (!\is_array($page)) {
                return null;
            }

            $postId = $page['post_id'] ?? null;

            return \is_scalar($postId) && $postId !== '' ? (string) $postId : null;
        };
    }

    /** @return list<array{type: string, path: string}> */
    private function differences(BridgeConfig $config, Report $report): array
    {
        $diffs = [];
        $expected = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
            $path = $this->pathFor($config, $file);

            if (!is_file($path)) {
                $diffs[] = ['type' => 'missing', 'path' => $file->relativePath];
                continue;
            }

            $contents = file_get_contents($path);

            if ($contents === false || $contents !== $file->contents) {
                $diffs[] = ['type' => 'modified', 'path' => $file->relativePath];
            }
        }

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (!\array_key_exists($relativePath, $expected) && $this->hasGeneratedMarker($path)) {
                $diffs[] = ['type' => 'orphan', 'path' => $relativePath];
            }
        }

        return $diffs;
    }

    private function writeGeneratedFiles(BridgeConfig $config, Report $report): void
    {
        if (!is_dir($config->outputDir) && !mkdir($config->outputDir, 0775, true) && !is_dir($config->outputDir)) {
            $this->fail("E102: failed to create output directory {$config->outputDir}", 1);
        }

        foreach ($report->files() as $file) {
            $path = $this->pathFor($config, $file);
            $tmp = $path . '.tmp';

            if (file_put_contents($tmp, $file->contents) === false) {
                $this->fail("E102: failed to write generated file {$tmp}", 1);
            }

            if (!rename($tmp, $path)) {
                $this->fail("E102: failed to move generated file {$tmp} to {$path}", 1);
            }

            $this->line("write: {$file->relativePath}");
        }
    }

    private function deleteOrphans(BridgeConfig $config, Report $report): void
    {
        $expected = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
        }

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (\array_key_exists($relativePath, $expected) || !$this->hasGeneratedMarker($path)) {
                continue;
            }

            if (!unlink($path)) {
                $this->fail("E102: failed to delete orphan generated file {$relativePath}", 1);
            }

            $this->line("delete: {$relativePath}");
        }
    }

    /** @return list<string> */
    private function generatedPhpFiles(BridgeConfig $config): array
    {
        if (!is_dir($config->outputDir)) {
            return [];
        }

        $files = [];
        $iterator = new FilesystemIterator($config->outputDir, FilesystemIterator::SKIP_DOTS);

        foreach ($iterator as $fileInfo) {
            if (!$fileInfo instanceof SplFileInfo || !$fileInfo->isFile() || $fileInfo->getExtension() !== 'php') {
                continue;
            }

            $files[] = $fileInfo->getPathname();
        }

        sort($files, SORT_STRING);

        return $files;
    }

    private function hasGeneratedMarker(string $path): bool
    {
        $contents = file_get_contents($path);

        return \is_string($contents) && str_contains($contents, self::GENERATED_MARKER);
    }

    private function pathFor(BridgeConfig $config, GeneratedFile $file): string
    {
        return rtrim($config->outputDir, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR . $file->relativePath;
    }

    private function printDiagnostics(Report $report): void
    {
        foreach ($report->errors() as $error) {
            $this->line($error);
        }

        foreach ($report->warnings() as $warning) {
            $this->line($warning);
        }

        foreach ($report->infos() as $info) {
            $this->line($info);
        }
    }

    /** @param list<array{type: string, path: string}> $diffs */
    private function printDifferences(array $diffs): void
    {
        foreach ($diffs as $diff) {
            $this->line($diff['type'] . ': ' . $diff['path']);
        }
    }

    private function line(string $message): void
    {
        $this->callWpCli('line', $message);
    }

    private function success(string $message): void
    {
        $this->callWpCli('success', $message);
    }

    private function fail(string $message, int $status): never
    {
        $this->line($message);
        $this->halt($status);

        throw new AcfBridgeRuntimeException($message);
    }

    private function halt(int $status): void
    {
        $callback = ['WP_CLI', 'halt'];

        if (!\is_callable($callback)) {
            throw new LogicException('WP_CLI::halt() is not available');
        }

        $callback($status);
    }

    private function callWpCli(string $method, string $message): void
    {
        $callback = ['WP_CLI', $method];

        if (!\is_callable($callback)) {
            throw new LogicException("WP_CLI::{$method}() is not available");
        }

        $callback($message);
    }
}
