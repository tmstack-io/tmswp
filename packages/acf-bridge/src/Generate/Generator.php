<?php

declare(strict_types=1);

namespace TMSWP\AcfBridge\Generate;

use TMSWP\AcfBridge\BridgeConfig;
use TMSWP\AcfBridge\Json\FieldDefinition;
use TMSWP\AcfBridge\Json\FieldGroup;
use TMSWP\AcfBridge\Manifest\ManagedKeyCollector;
use TMSWP\AcfBridge\Mapping\GenerationTarget;
use TMSWP\AcfBridge\Mapping\LocationResolver;
use TMSWP\AcfBridge\Mapping\TargetKind;

final class Generator
{
    private const GENERATED_MARKER = '@generated by tmswp/acf-bridge';

    /** @var list<string> */
    private const RESERVED_SYMBOLS = [
        'of',
        'instance',
        'value',
        'rawValue',
        'update',
        'delete',
        'has',
        'acfId',
    ];

    /** @var list<string> */
    private const KNOWN_FIELD_TYPES = [
        'text',
        'textarea',
        'email',
        'url',
        'password',
        'wysiwyg',
        'oembed',
        'number',
        'range',
        'true_false',
        'select',
        'checkbox',
        'radio',
        'button_group',
        'image',
        'file',
        'gallery',
        'link',
        'post_object',
        'page_link',
        'relationship',
        'taxonomy',
        'user',
        'date_picker',
        'date_time_picker',
        'time_picker',
        'color_picker',
        'message',
        'tab',
        'accordion',
        'group',
        'repeater',
        'flexible_content',
        'clone',
    ];

    public function __construct(
        private readonly LocationResolver $locations = new LocationResolver(),
        private readonly TypeMapper $types = new TypeMapper(),
    ) {}

    /**
     * @param list<FieldGroup> $groups
     */
    public function generate(array $groups, GeneratorContext $context): Report
    {
        $errors = [];
        $warnings = [];
        $infos = [];
        $groups = (new CloneResolver())->resolve($groups, $errors);
        $buckets = $this->buckets($groups, $context->config, $errors, $warnings);
        $files = [];

        foreach ($buckets as $bucket) {
            $accessors = $this->accessorsFor($bucket, $context->config, $errors, $warnings);
            $files[] = new GeneratedFile(
                $bucket->target->className . '.php',
                $this->renderClass($bucket, $accessors, $context),
            );
        }

        $files[] = new GeneratedFile('AcfManifest.php', $this->renderManifest($groups, $context));

        usort($files, static fn(GeneratedFile $a, GeneratedFile $b): int => $a->relativePath <=> $b->relativePath);

        return new Report($files, $errors, $warnings, $infos);
    }

    /**
     * @param list<FieldGroup> $groups
     * @param list<string> $errors
     * @param list<string> $warnings
     *
     * @return list<TargetBucket>
     */
    private function buckets(array $groups, BridgeConfig $config, array &$errors, array &$warnings): array
    {
        /** @var array<string, TargetBucket> $buckets */
        $buckets = [];
        /** @var array<string, string> $classTargets */
        $classTargets = [];

        foreach ($groups as $group) {
            if (!$group->active) {
                $warnings[] = "W011: inactive ACF field group '{$group->key}' was skipped";
                continue;
            }

            $targets = $this->locations->resolveWithWarnings($group, $config, $warnings);

            if ($targets === []) {
                $warnings[] = "W002: ACF field group '{$group->key}' location could not be resolved";
                continue;
            }

            if (\count($targets) > 1 && \array_key_exists($group->key, $config->classMap)) {
                $errors[] = "E003: classMap for '{$group->key}' is only allowed for a single target group";
                continue;
            }

            foreach ($targets as $target) {
                $targetKey = $this->targetKey($target);

                if (!$this->isClassName($target->className)) {
                    $errors[] = "E003: target {$targetKey} resolves to invalid class name '{$target->className}'";
                    continue;
                }

                $registeredTarget = $classTargets[$target->className] ?? null;

                if ($registeredTarget !== null && $registeredTarget !== $targetKey) {
                    $errors[] = "E003: class name '{$target->className}' is used by both {$registeredTarget} and {$targetKey}";
                    continue;
                }

                $classTargets[$target->className] = $targetKey;
                $buckets[$targetKey] ??= new TargetBucket($target);
                $buckets[$targetKey]->addGroup($group);
            }
        }

        ksort($buckets, SORT_STRING);

        return array_values($buckets);
    }

    /**
     * @param list<string> $errors
     * @param list<string> $warnings
     *
     * @return list<AccessorDefinition>
     */
    private function accessorsFor(TargetBucket $bucket, BridgeConfig $config, array &$errors, array &$warnings): array
    {
        $accessors = [];
        /** @var array<string, string> $fieldNames */
        $fieldNames = [];
        /** @var array<string, true> $symbols */
        $symbols = [];

        foreach (self::RESERVED_SYMBOLS as $symbol) {
            $symbols[$symbol] = true;
        }

        foreach ($bucket->groups() as $group) {
            foreach ($group->fields as $field) {
                if (!$this->types->storesValue($field)) {
                    continue;
                }

                if ($field->type === 'clone') {
                    $errors[] = "E004: clone field '{$field->name}' in group '{$group->key}' cannot be resolved yet";
                    continue;
                }

                if (!\in_array($field->type, self::KNOWN_FIELD_TYPES, true)) {
                    $warnings[] = "W005: unknown ACF field type '{$field->type}' for '{$field->name}' was generated as mixed";
                }

                $registeredGroup = $fieldNames[$field->name] ?? null;

                if ($registeredGroup !== null) {
                    $errors[] = "E001: duplicate ACF field '{$field->name}' for {$this->targetKey($bucket->target)} in groups {$registeredGroup} and {$group->key}";
                    continue;
                }

                $fieldNames[$field->name] = $group->key;
                $accessor = $this->accessorFor($group, $field, $config, $symbols, $errors, $warnings);

                if ($accessor instanceof AccessorDefinition) {
                    $accessors[] = $accessor;
                }
            }
        }

        return $accessors;
    }

    /**
     * @param array<string, true> $symbols
     * @param list<string> $errors
     * @param list<string> $warnings
     */
    private function accessorFor(
        FieldGroup $group,
        FieldDefinition $field,
        BridgeConfig $config,
        array &$symbols,
        array &$errors,
        array &$warnings,
    ): ?AccessorDefinition {
        $methodMapKey = $group->key . '.' . $field->name;
        $methodName = $config->methodNameMap[$methodMapKey] ?? null;
        $constName = NameConverter::constName($field->name);

        if ($methodName === null) {
            if (!NameConverter::isAccessorEligible($field->name) || $constName === null) {
                $warnings[] = "W009: ACF field '{$field->name}' in group '{$group->key}' is not ASCII snake_case; accessor was skipped";

                return null;
            }

            $methodName = NameConverter::methodName($field->name);
        } elseif (!$this->isMethodName($methodName)) {
            $errors[] = "E002: methodNameMap '{$methodMapKey}' resolves to invalid method '{$methodName}'";

            return null;
        } else {
            $constName ??= $this->constNameFromMethod($methodName);
        }

        $keyConstName = 'KEY_' . $constName;
        $setterName = 'set' . ucfirst($methodName);
        $mapping = $this->types->map($field);
        $dateTimeMethodName = $mapping->dateTimeAccessor ? $methodName . 'AsDateTime' : null;
        $declaredSymbols = [$constName, $keyConstName, $methodName, $setterName];

        if ($dateTimeMethodName !== null) {
            $declaredSymbols[] = $dateTimeMethodName;
        }

        foreach ($declaredSymbols as $symbol) {
            if (\array_key_exists($symbol, $symbols)) {
                $errors[] = "E002: generated symbol '{$symbol}' for ACF field '{$field->name}' in group '{$group->key}' is duplicated";

                return null;
            }
        }

        foreach ($declaredSymbols as $symbol) {
            $symbols[$symbol] = true;
        }

        return new AccessorDefinition(
            groupKey: $group->key,
            groupTitle: $group->title,
            sourceFile: $group->sourceFile,
            field: $field,
            constName: $constName,
            keyConstName: $keyConstName,
            methodName: $methodName,
            setterName: $setterName,
            dateTimeMethodName: $dateTimeMethodName,
            mapping: $mapping,
        );
    }

    /** @param list<AccessorDefinition> $accessors */
    private function renderClass(TargetBucket $bucket, array $accessors, GeneratorContext $context): string
    {
        $target = $bucket->target;
        $sourceLines = $this->sourceLines($bucket->groups());
        $optionsPostId = $target->kind === TargetKind::Options ? $this->optionsPostId($target->subtype, $context) : null;

        $lines = $this->headerLines(
            "{$target->className} — ACF typed accessors for {$this->targetDescription($target)}.",
            $context->config->namespace,
            $sourceLines,
        );
        $imports = $this->phpstanImports($accessors);

        $lines[] = 'use TMSWP\\AcfBridge\\AcfFieldAccess;';
        $lines[] = '';

        if ($imports !== []) {
            $lines[] = '/**';

            foreach ($imports as $import) {
                $lines[] = " * @phpstan-import-type {$import} from \\TMSWP\\AcfBridge\\AcfTypes";
            }

            $lines[] = ' */';
        }

        $lines[] = "final class {$target->className}";
        $lines[] = '{';
        $lines[] = '    use AcfFieldAccess;';

        foreach ($accessors as $accessor) {
            $lines[] = '';
            $lines[] = '    /** ' . $this->fieldDescription($accessor) . ' */';
            $lines[] = "    public const {$accessor->constName} = " . $this->phpString($accessor->field->name) . ';';
            $lines[] = "    public const {$accessor->keyConstName} = " . $this->phpString($accessor->field->key) . ';';
        }

        $lines = array_merge($lines, $this->factoryLines($target, $optionsPostId));

        foreach ($accessors as $accessor) {
            $lines = array_merge($lines, $this->getterLines($accessor));
            $lines = array_merge($lines, $this->setterLines($accessor));

            if ($accessor->dateTimeMethodName !== null) {
                $lines = array_merge($lines, $this->dateTimeGetterLines($accessor));
            }
        }

        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param list<FieldGroup> $groups
     *
     * @return list<string>
     */
    private function sourceLines(array $groups): array
    {
        /** @var array<string, string> $sources */
        $sources = [];

        foreach ($groups as $group) {
            $sources[basename($group->sourceFile)] = basename($group->sourceFile) . ' (' . $group->title . ')';
        }

        ksort($sources, SORT_STRING);

        return array_values($sources);
    }

    /**
     * @param list<string> $sourceLines
     *
     * @return list<string>
     */
    private function headerLines(string $title, string $namespace, array $sourceLines, string $extra = ''): array
    {
        $lines = [
            '<?php',
            '',
            '/**',
            " * {$title}",
            ' *',
            ' * ' . self::GENERATED_MARKER,
        ];

        if ($extra !== '') {
            $lines[] = ' * ' . $extra;
        }

        $lines[] = ' *';
        $lines[] = ' * このファイルは自動生成。手で編集しないこと(次回 sync で上書きされる)。';
        $lines[] = ' * 再生成: wp tmswp acf sync  (composer acf:sync)';
        $lines[] = ' *';
        $lines[] = ' * sources:';

        if ($sourceLines === []) {
            $lines[] = ' *   (none)';
        } else {
            foreach ($sourceLines as $sourceLine) {
                $lines[] = " *   {$sourceLine}";
            }
        }

        $lines[] = ' */';
        $lines[] = '';
        $lines[] = 'declare(strict_types=1);';
        $lines[] = '';
        $lines[] = "namespace {$namespace};";
        $lines[] = '';

        return $lines;
    }

    /**
     * @param list<AccessorDefinition> $accessors
     *
     * @return list<string>
     */
    private function phpstanImports(array $accessors): array
    {
        $imports = [];

        foreach ($accessors as $accessor) {
            $haystack = $accessor->mapping->getterDocType . ' ' . $accessor->mapping->setterDocType;

            foreach (['AcfImage', 'AcfFile', 'AcfLink', 'AcfChoice', 'AcfUserArray', 'AcfColorRgba'] as $type) {
                if (str_contains($haystack, $type)) {
                    $imports[$type] = $type;
                }
            }
        }

        ksort($imports, SORT_STRING);

        return array_values($imports);
    }

    /** @return list<string> */
    private function factoryLines(GenerationTarget $target, ?string $optionsPostId): array
    {
        if ($target->kind === TargetKind::Post) {
            return [
                '',
                '    public static function of(\\WP_Post|int $post): self',
                '    {',
                '        return new self($post instanceof \\WP_Post ? (int) $post->ID : $post);',
                '    }',
            ];
        }

        if ($target->kind === TargetKind::Term) {
            return [
                '',
                '    public static function of(\\WP_Term|int $term): self',
                '    {',
                '        $termId = $term instanceof \\WP_Term ? (int) $term->term_id : $term;',
                '',
                '        return new self("term_{$termId}");',
                '    }',
            ];
        }

        if ($target->kind === TargetKind::User) {
            return [
                '',
                '    public static function of(\\WP_User|int $user): self',
                '    {',
                '        $userId = $user instanceof \\WP_User ? (int) $user->ID : $user;',
                '',
                '        return new self("user_{$userId}");',
                '    }',
            ];
        }

        return [
            '',
            '    public static function instance(): self',
            '    {',
            '        return new self(' . $this->phpString($optionsPostId ?? 'option') . ');',
            '    }',
        ];
    }

    /** @return list<string> */
    private function getterLines(AccessorDefinition $accessor): array
    {
        $mapping = $accessor->mapping;
        $lines = [
            '',
            '    /**',
            '     * ' . $this->fieldDescription($accessor),
            '     *',
            "     * @return {$mapping->getterDocType}",
            '     */',
            "    public function {$accessor->methodName}(): {$mapping->getterNativeType}",
            '    {',
        ];

        foreach ($this->getterBody($accessor) as $bodyLine) {
            $lines[] = '        ' . $bodyLine;
        }

        $lines[] = '    }';

        return $lines;
    }

    /** @return list<string> */
    private function getterBody(AccessorDefinition $accessor): array
    {
        $const = "self::{$accessor->constName}";
        $mapping = $accessor->mapping;
        $objectClass = $this->objectClassFromDocType($mapping->getterDocType);

        if ($objectClass !== null) {
            return ["return \$this->acfObject({$const}, {$objectClass}::class);"];
        }

        if ($mapping->coercionHelper === 'value') {
            return ["return \$this->value({$const});"];
        }

        return ["return \$this->{$mapping->coercionHelper}({$const});"];
    }

    /** @return list<string> */
    private function setterLines(AccessorDefinition $accessor): array
    {
        $mapping = $accessor->mapping;
        $lines = [''];

        if ($mapping->setterDocType !== '') {
            $lines[] = '    /** @param ' . $mapping->setterDocType . ' $value */';
        }

        $lines[] = "    public function {$accessor->setterName}({$mapping->setterNativeType} \$value): void";
        $lines[] = '    {';

        if ($mapping->dateRawFormat !== '') {
            $lines[] = "        \$this->acfUpdateDate(self::{$accessor->constName}, \$value, " . $this->phpString($mapping->dateRawFormat) . ');';
        } else {
            $lines[] = "        \$this->acfUpdate(self::{$accessor->constName}, \$value);";
        }

        $lines[] = '    }';

        return $lines;
    }

    /** @return list<string> */
    private function dateTimeGetterLines(AccessorDefinition $accessor): array
    {
        $methodName = $accessor->dateTimeMethodName;

        if ($methodName === null) {
            return [];
        }

        return [
            '',
            "    public function {$methodName}(): ?\\DateTimeImmutable",
            '    {',
            "        return \$this->acfDateTime(self::{$accessor->constName}, " . $this->phpString($accessor->mapping->dateRawFormat) . ');',
            '    }',
        ];
    }

    /**
     * 管理キーの一覧(AcfManifest)を生成する。管理キーは`wp tmswp acf check`のE101と同じManagedKeyCollectorで集める。
     *
     * @param list<FieldGroup> $groups cloneを解決したグループ
     */
    private function renderManifest(array $groups, GeneratorContext $context): string
    {
        $managedKeys = (new ManagedKeyCollector($this->locations, $this->types))->collect($groups, $context->config);
        $lines = $this->headerLines(
            'AcfManifest — ACF managed keys.',
            $context->config->namespace,
            ['source-hash sha256:' . $context->sourceHash],
            'source-hash: sha256:' . $context->sourceHash,
        );
        $usesObjectType = false;

        foreach ($managedKeys as $managedKey) {
            if ($managedKey->objectType !== null) {
                $usesObjectType = true;
                break;
            }
        }

        $lines[] = 'use TMSWP\\AcfBridge\\Manifest\\ManagedKey;';

        if ($usesObjectType) {
            $lines[] = 'use TMSWP\\Core\\Meta\\ObjectType;';
        }

        $lines[] = '';
        $lines[] = 'final class AcfManifest';
        $lines[] = '{';
        $lines[] = '    /** @return list<ManagedKey> */';
        $lines[] = '    public static function managedKeys(): array';
        $lines[] = '    {';
        $lines[] = '        return [';

        foreach ($managedKeys as $managedKey) {
            $lines[] = '            new ManagedKey('
                . ($managedKey->objectType !== null ? 'ObjectType::' . $managedKey->objectType->name : 'null') . ', '
                . $this->phpString($managedKey->objectSubtype) . ', '
                . $this->phpString($managedKey->metaKey) . ', '
                . $this->phpString($managedKey->fieldKey) . ', '
                . $this->phpString($managedKey->groupKey)
                . '),';
        }

        $lines[] = '        ];';
        $lines[] = '    }';
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    /**
     * オプションページのACFのpost_id。GeneratorContext::$optionsPagePostIds(acf-jsonのui_options_pageと
     * BridgeConfigのoptionsPagePostIds)に無ければ'option'。
     */
    private function optionsPostId(string $menuSlug, GeneratorContext $context): string
    {
        return $context->optionsPagePostIds[$menuSlug] ?? 'option';
    }

    private function objectClassFromDocType(string $docType): ?string
    {
        foreach (['\\WP_Post', '\\WP_Term', '\\WP_User'] as $class) {
            if ($docType === $class . '|null') {
                return $class;
            }
        }

        return null;
    }

    private function targetDescription(GenerationTarget $target): string
    {
        return match ($target->kind) {
            TargetKind::Post => 'post_type ' . $this->phpString($target->subtype),
            TargetKind::Term => 'taxonomy ' . $this->phpString($target->subtype),
            TargetKind::User => 'users',
            TargetKind::Options => 'options_page ' . $this->phpString($target->subtype),
        };
    }

    private function fieldDescription(AccessorDefinition $accessor): string
    {
        $label = $accessor->field->label !== '' ? $accessor->field->label : $accessor->field->name;

        return "{$label} ({$accessor->field->type}, {$accessor->groupKey})";
    }

    private function targetKey(GenerationTarget $target): string
    {
        return $target->kind->value . ':' . $target->subtype;
    }

    private function isClassName(string $className): bool
    {
        return preg_match('/^[A-Z][A-Za-z0-9]*$/', $className) === 1;
    }

    private function isMethodName(string $methodName): bool
    {
        return preg_match('/^[a-z][A-Za-z0-9]*$/', $methodName) === 1;
    }

    private function constNameFromMethod(string $methodName): string
    {
        $snake = preg_replace('/(?<!^)[A-Z]/', '_$0', $methodName);

        return strtoupper((string) $snake);
    }

    private function phpString(string $value): string
    {
        return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
    }
}
