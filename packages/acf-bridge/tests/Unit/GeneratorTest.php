<?php

declare(strict_types=1);

namespace TMSWP\AcfBridge\Tests\Unit;

use TMSWP\AcfBridge\BridgeConfig;
use TMSWP\AcfBridge\Generate\GeneratedFile;
use TMSWP\AcfBridge\Generate\Generator;
use TMSWP\AcfBridge\Generate\GeneratorContext;
use TMSWP\AcfBridge\Json\AcfJsonRepository;
use TMSWP\AcfBridge\Json\FieldGroup;
use TMSWP\Core\Tests\Support\UnitTestCase;

final class GeneratorTest extends UnitTestCase
{
    public function testFixtureSnapshotMatchesExpectedApp(): void
    {
        $repository = new AcfJsonRepository([__DIR__ . '/../fixtures/acf-json']);
        $config = new BridgeConfig(
            jsonDirs: [],
            outputDir: __DIR__ . '/../fixtures/expected-app/Acf',
            namespace: 'App\\Acf',
            methodNameMap: ['group_product.店舗名' => 'storeName'],
        );
        $report = (new Generator())->generate(
            $repository->fieldGroups(),
            new GeneratorContext(
                config: $config,
                optionsPagePostIds: $repository->optionsPagePostIds(),
                sourceHash: $repository->sourceHash(),
            ),
        );

        self::assertSame([], $report->errors());
        self::assertSame([], $report->warnings());
        self::assertSame($this->expectedFixtureFiles(), $this->filesByPath($report->files()));
    }

    public function testItGeneratesDeterministicAccessorClassesAndManifest(): void
    {
        $config = new BridgeConfig(
            jsonDirs: [],
            outputDir: $this->createTempDirectory('acf-output'),
            namespace: 'App\\Acf',
            methodNameMap: ['group_product.店舗名' => 'storeName'],
        );
        $context = new GeneratorContext(
            config: $config,
            optionsPagePostIds: ['theme-settings' => 'theme_settings'],
            sourceHash: 'abc123',
        );
        $groups = [
            $this->group([
                'key' => 'group_product',
                'title' => '製品情報',
                'location' => [[['param' => 'post_type', 'operator' => '==', 'value' => 'product']]],
                'fields' => [
                    ['key' => 'field_price', 'name' => 'price', 'label' => '価格', 'type' => 'number'],
                    ['key' => 'field_visual', 'name' => 'main_visual', 'label' => 'メイン画像', 'type' => 'image', 'return_format' => 'array'],
                    ['key' => 'field_published', 'name' => 'published_at', 'label' => '公開日時', 'type' => 'date_time_picker'],
                    [
                        'key' => 'field_stores',
                        'name' => 'stores',
                        'label' => '店舗',
                        'type' => 'repeater',
                        'sub_fields' => [
                            ['key' => 'field_shop', 'name' => 'shop_name', 'label' => '店舗名', 'type' => 'text'],
                            ['key' => 'field_tel', 'name' => 'tel', 'label' => 'TEL', 'type' => 'text'],
                        ],
                    ],
                    ['key' => 'field_store_name', 'name' => '店舗名', 'label' => '店舗名', 'type' => 'text'],
                ],
            ], 'acf-json/group_product.json'),
            $this->group([
                'key' => 'group_options',
                'title' => 'サイト設定',
                'location' => [[['param' => 'options_page', 'operator' => '==', 'value' => 'theme-settings']]],
                'fields' => [
                    ['key' => 'field_logo', 'name' => 'site_logo', 'label' => 'ロゴ', 'type' => 'image', 'return_format' => 'id'],
                ],
            ], 'acf-json/group_options.json'),
            $this->group([
                'key' => 'group_inactive',
                'title' => '無効',
                'active' => false,
                'location' => [[['param' => 'post_type', 'operator' => '==', 'value' => 'post']]],
                'fields' => [
                    ['key' => 'field_ignored', 'name' => 'ignored', 'label' => '無視', 'type' => 'text'],
                ],
            ], 'acf-json/group_inactive.json'),
        ];

        $report = (new Generator())->generate($groups, $context);
        $secondReport = (new Generator())->generate($groups, $context);

        self::assertSame([], $report->errors());
        self::assertSame(["W011: inactive ACF field group 'group_inactive' was skipped"], $report->warnings());
        self::assertSame($this->filesByPath($report->files()), $this->filesByPath($secondReport->files()));

        $files = $this->filesByPath($report->files());
        self::assertArrayHasKey('ProductFields.php', $files);
        self::assertArrayHasKey('ThemeSettingsOptions.php', $files);
        self::assertArrayHasKey('AcfManifest.php', $files);

        $product = $files['ProductFields.php'];
        self::assertStringContainsString('@generated by tmswp/acf-bridge', $product);
        self::assertStringContainsString('namespace App\\Acf;', $product);
        self::assertStringContainsString('@phpstan-import-type AcfImage from \\TMSWP\\AcfBridge\\AcfTypes', $product);
        self::assertStringContainsString("public const PRICE = 'price';", $product);
        self::assertStringContainsString("public const STORE_NAME = '店舗名';", $product);
        self::assertStringContainsString('public static function of(\\WP_Post|int $post): self', $product);
        self::assertStringContainsString('public function price(): int|float|null', $product);
        self::assertStringContainsString('public function mainVisual(): ?array', $product);
        self::assertStringContainsString('@return list<array{shop_name: string, tel: string}>', $product);
        self::assertStringContainsString('public function publishedAtAsDateTime(): ?\\DateTimeImmutable', $product);
        self::assertStringContainsString('public function storeName(): string', $product);

        $options = $files['ThemeSettingsOptions.php'];
        self::assertStringContainsString("return new self('theme_settings');", $options);
        self::assertStringContainsString('public function siteLogo(): ?int', $options);

        $manifest = $files['AcfManifest.php'];
        self::assertStringContainsString('source-hash: sha256:abc123', $manifest);
        self::assertStringContainsString("new ManagedKey(ObjectType::Post, 'product', 'price', 'field_price', 'group_product')", $manifest);
        self::assertStringContainsString("new ManagedKey(null, 'theme-settings', 'site_logo', 'field_logo', 'group_options')", $manifest);
    }

    /**
     * objectのlist(relationship・post_object・taxonomy・userの複数・return_format=object)のgetterは、要素のクラスを渡して
     * acfObjectList()を呼ぶ(要素ごとにinstanceofを検査する)。単一のobjectはacfObject()、IDのlistはacfIntList()のまま。
     */
    public function testObjectListGettersPassTheElementClass(): void
    {
        $context = new GeneratorContext(
            config: new BridgeConfig(jsonDirs: [], outputDir: $this->createTempDirectory('acf-output'), namespace: 'App\\Acf'),
            optionsPagePostIds: [],
            sourceHash: 'abc123',
        );
        $group = $this->group([
            'key' => 'group_links',
            'title' => 'Links',
            'location' => [[['param' => 'post_type', 'operator' => '==', 'value' => 'product']]],
            'fields' => [
                ['key' => 'field_related', 'name' => 'related', 'label' => 'Related', 'type' => 'relationship', 'return_format' => 'object'],
                ['key' => 'field_posts', 'name' => 'posts', 'label' => 'Posts', 'type' => 'post_object', 'multiple' => 1, 'return_format' => 'object'],
                ['key' => 'field_terms', 'name' => 'terms', 'label' => 'Terms', 'type' => 'taxonomy', 'field_type' => 'checkbox', 'return_format' => 'object'],
                ['key' => 'field_users', 'name' => 'users', 'label' => 'Users', 'type' => 'user', 'multiple' => 1, 'return_format' => 'object'],
                ['key' => 'field_post', 'name' => 'post', 'label' => 'Post', 'type' => 'post_object', 'return_format' => 'object'],
                ['key' => 'field_ids', 'name' => 'ids', 'label' => 'IDs', 'type' => 'relationship', 'return_format' => 'id'],
            ],
        ], 'acf-json/group_links.json');

        $report = (new Generator())->generate([$group], $context);

        self::assertSame([], $report->errors());
        $product = $this->filesByPath($report->files())['ProductFields.php'];
        self::assertStringContainsString('return $this->acfObjectList(self::RELATED, \\WP_Post::class);', $product);
        self::assertStringContainsString('return $this->acfObjectList(self::POSTS, \\WP_Post::class);', $product);
        self::assertStringContainsString('return $this->acfObjectList(self::TERMS, \\WP_Term::class);', $product);
        self::assertStringContainsString('return $this->acfObjectList(self::USERS, \\WP_User::class);', $product);
        self::assertStringContainsString('return $this->acfObject(self::POST, \\WP_Post::class);', $product);
        self::assertStringContainsString('return $this->acfIntList(self::IDS);', $product);
        self::assertStringNotContainsString('acfList(', $product);
    }

    /** @return array<string, string> */
    private function expectedFixtureFiles(): array
    {
        $baseDir = __DIR__ . '/../fixtures/expected-app/Acf';

        return [
            'AcfManifest.php' => $this->readFixture($baseDir . '/AcfManifest.php'),
            'ProductFields.php' => $this->readFixture($baseDir . '/ProductFields.php'),
            'ThemeSettingsOptions.php' => $this->readFixture($baseDir . '/ThemeSettingsOptions.php'),
        ];
    }

    private function readFixture(string $path): string
    {
        $contents = file_get_contents($path);

        if ($contents === false) {
            self::fail("fixture を読み込めません: {$path}");
        }

        return $contents;
    }

    /** @param array<string, mixed> $data */
    private function group(array $data, string $sourceFile): FieldGroup
    {
        return FieldGroup::fromArray($data, $sourceFile);
    }

    /**
     * @param list<GeneratedFile> $files
     *
     * @return array<string, string>
     */
    private function filesByPath(array $files): array
    {
        $indexed = [];

        foreach ($files as $file) {
            $indexed[$file->relativePath] = $file->contents;
        }

        ksort($indexed, SORT_STRING);

        return $indexed;
    }
}
